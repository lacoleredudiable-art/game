"""Deterministic generator for the Deneme Sahnesi open lava plain.
All coordinates in UNITY space (left-handed, Y up, metres). OBJ files are written with x negated
(Unity's OBJ importer negates x again), so Unity sees exactly these coordinates.
Outputs: Ground_Near.obj, Ground_Far.obj, LavaCracks.obj, Skyline.obj, EdgeMist.obj, DenemeSahnesiLayout.json
"""
