rng=np.random.default_rng(20261001)

# ---------- height field ----------
def vnoise_factory(seed):
    r=np.random.default_rng(seed); P=r.random((256,256))
    def n(x,y):
        xi=np.floor(x).astype(int); yi=np.floor(y).astype(int); xf=x-xi; yf=y-yi
        u=xf*xf*(3-2*xf); v=yf*yf*(3-2*yf)
        a=P[xi%256,yi%256]; b=P[(xi+1)%256,yi%256]; c=P[xi%256,(yi+1)%256]; d=P[(xi+1)%256,(yi+1)%256]
        return (a*(1-u)+b*u)*(1-v)+(c*(1-u)+d*u)*v
    return n
N1=vnoise_factory(1); N2=vnoise_factory(2)
def fbm(n,x,y,oct=4):
    s=0; a=0.5; f=1.0
    for _ in range(oct): s+=a*(n(x*f,y*f)-0.5); a*=0.5; f*=2.03
    return s
def height(x,z):
    x=np.asarray(x,float); z=np.asarray(z,float); r=np.hypot(x,z)
    near=fbm(N1,x/9+50,z/9+50)*0.9                     # +-0.4 m gentle basalt swell
    flat=np.clip((r-5)/10,0,1)                            # hero area flat
    mid=fbm(N2,x/40+10,z/40+10,5)*6*np.clip((r-35)/40,0,1)   # rolling beyond the boundary
    far=np.clip((r-150)/500,0,1)**1.3*14*(0.6+fbm(N1,x/180,z/180,3)+0.4)  # horizon rise
    return near*flat+mid+far

# ---------- polar ground mesh ----------
radii=list(np.arange(0,15.01,0.9))
while radii[-1]<1000: radii.append(radii[-1]*1.06)
radii=np.array(radii); SEG=160
split=int(np.argmin(np.abs(radii-75)))
def write_obj(path,V,UV,F,Nrm=None,header=''):
    with open(path,'w') as f:
        f.write(f'# {header}\n# generated by gen_layout.py (box). x is negated for Unity OBJ import.\n')
        for v in V: f.write(f'v {-v[0]:.4f} {v[1]:.4f} {v[2]:.4f}\n')
        for t in UV: f.write(f'vt {t[0]:.5f} {t[1]:.5f}\n')
        if Nrm is not None:
            for n in Nrm: f.write(f'vn {-n[0]:.4f} {n[1]:.4f} {n[2]:.4f}\n')
        for a,b,c in F:
            a+=1;b+=1;c+=1
            if Nrm is not None: f.write(f'f {a}/{a}/{a} {b}/{b}/{b} {c}/{c}/{c}\n')
            else: f.write(f'f {a}/{a} {b}/{b} {c}/{c}\n')
def vnormals(V,F):
    n=np.zeros_like(V); fn=np.cross(V[F[:,1]]-V[F[:,0]],V[F[:,2]]-V[F[:,0]])
    for k in range(3): np.add.at(n,F[:,k],fn)
    return n/np.linalg.norm(n,axis=1,keepdims=True)
def polar_ring_mesh(r_list):
    th=np.linspace(0,2*np.pi,SEG,endpoint=False)
    V=[];UV=[]
    centre = r_list[0]==0
    rows=[]
    for r in r_list:
        if r==0:
            rows.append([len(V)]); V.append([0,height(0,0),0]); UV.append([0,0]); continue
        row=[]
        for t in th:
            x,z=r*math.cos(t),r*math.sin(t); row.append(len(V)); V.append([x,float(height(x,z)),z]); UV.append([x,z])
        rows.append(row)
    F=[]
    for i in range(len(rows)-1):
        A,B=rows[i],rows[i+1]
        for j in range(SEG):
            j2=(j+1)%SEG
            if len(A)==1: F.append([A[0],B[j2],B[j]]) # Unity-space winding: clockwise seen from +Y
            else:
                F.append([A[j],B[j2],B[j]]); F.append([A[j],A[j2],B[j2]])
    V=np.array(V,float); F=np.array(F)
    # Unity front faces are clockwise from the viewer; check normal points up with LH cross
    nrm=vnormals(V,F)
    if nrm[:,1].mean()>0:  # RH cross up => CCW from above in RH terms; flip to CW for Unity
        F=F[:,[0,2,1]]
    nrm=-vnormals(V,F) if vnormals(V,F)[:,1].mean()<0 else vnormals(V,F)
    return V,np.array(UV),F,nrm
V,UV,F,Nn=polar_ring_mesh(radii[:split+1])
write_obj(f'{OUT}/Ground_Near.obj',V,UV,F,Nn,f'Deneme Sahnesi near ground r<= {radii[split]:.1f} m, {len(F)} tris, UV0 = world XZ metres')
print('near',len(F),'tris r',radii[split])
V2,UV2,F2,N2n=polar_ring_mesh(radii[split:])
write_obj(f'{OUT}/Ground_Far.obj',V2,UV2,F2,N2n,f'Deneme Sahnesi far ground {radii[split]:.1f}..{radii[-1]:.0f} m, {len(F2)} tris')
print('far',len(F2),'tris to',radii[-1])

# ---------- lava cracks (ribbons) ----------
_TH=np.linspace(0,2*np.pi,SEG,endpoint=False)
_GRID=np.array([[float(height(r*math.cos(t),r*math.sin(t))) for t in _TH] for r in radii])
def mesh_h(x,z):
    r=math.hypot(x,z); t=math.atan2(z,x)%(2*np.pi)
    i=max(0,min(len(radii)-2,int(np.searchsorted(radii,r)-1))); fr=(r-radii[i])/(radii[i+1]-radii[i])
    j=int(t/(2*np.pi)*SEG)%SEG; j2=(j+1)%SEG; ft=t/(2*np.pi)*SEG-int(t/(2*np.pi)*SEG)
    if i==0 and radii[0]==0:
        a=_GRID[0,0]; b=_GRID[1,j]*(1-ft)+_GRID[1,j2]*ft; return a*(1-fr)+b*fr
    a=_GRID[i,j]*(1-ft)+_GRID[i,j2]*ft; b=_GRID[i+1,j]*(1-ft)+_GRID[i+1,j2]*ft
    return max(a*(1-fr)+b*fr, float(height(x,z)))

cracks=[]
def walk(start,ang,length,width,depth=0):
    pts=[np.array(start,float)]; a=ang; step=0.6
    n=int(length/step)
    for i in range(n):
        a+=rng.normal(0,0.22); p=pts[-1]+step*np.array([math.cos(a),math.sin(a)])
        if np.hypot(*p)<2.2: break
        pts.append(p)
        if depth<2 and i>3 and rng.random()<0.07:
            walk(p,a+rng.choice([-1,1])*rng.uniform(0.6,1.3),length*rng.uniform(0.25,0.5),width*0.55,depth+1)
    cracks.append((np.array(pts),width))
# main fissure toward the dragon (+Z), leading line from foreground
walk((1.8,-5.5),math.radians(84),70,0.42)
walk((-2.5,-3.0),math.radians(100),55,0.28)
for k in range(10):
    a0=rng.uniform(0,2*np.pi); r0=rng.uniform(4,26)
    walk((r0*math.cos(a0),r0*math.sin(a0)),rng.uniform(0,2*np.pi),rng.uniform(8,26),rng.uniform(0.10,0.22))
for k in range(8):  # far cracks
    a0=rng.uniform(0,2*np.pi); r0=rng.uniform(30,70)
    walk((r0*math.cos(a0),r0*math.sin(a0)),rng.uniform(0,2*np.pi),rng.uniform(10,30),rng.uniform(0.15,0.35))
CV=[];CUV=[];CF=[]
for pts,w in cracks:
    if len(pts)<3: continue
    seglen=np.r_[0,np.cumsum(np.linalg.norm(np.diff(pts,axis=0),axis=1))]; L=seglen[-1]
    base=len(CV)
    for i,p in enumerate(pts):
        d=pts[min(i+1,len(pts)-1)]-pts[max(i-1,0)]; d/=np.linalg.norm(d)+1e-9; nrm=np.array([-d[1],d[0]])
        taper=min(1,seglen[i]/2.5,(L-seglen[i])/2.5)**0.7
        ww=w*max(taper,0.08)*(0.75+0.5*N1(seglen[i]*0.7+base*0.01,3.3))*(1+np.hypot(*p)/9)
        for s,u in ((-1,0.0),(1,1.0)):
            q=p+nrm*ww*0.5*s; CV.append([q[0],mesh_h(q[0],q[1])+0.03+0.002*math.hypot(q[0],q[1]),q[1]]); CUV.append([u,seglen[i]])
    for i in range(len(pts)-1):
        a=base+2*i; CF.append([a,a+1,a+3]); CF.append([a,a+3,a+2])
# hot spots (glowing pools), like the mood photo
for k in range(40):
    pts,w=cracks[rng.integers(0,len(cracks))]; p=pts[rng.integers(0,len(pts))]+rng.normal(0,0.6,2)
